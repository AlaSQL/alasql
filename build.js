/*
Builds dist/ from src/index.js with esbuild.

	yarn build-only

Outputs:
	dist/alasql.fs.js         CommonJS for Node; the externals stay require() calls
	dist/alasql.js            the browser file, in a UMD wrapper
	dist/alasql.min.js        the same, minified
	dist/alasql-worker.js     the web worker
	dist/precompile/index.js  alasql/precompile
	dist/alasql.d.ts, dist/alasql-echo.js, dist/alasql-prolog.js: copied

Adaptations to the esbuild workflow
- The UMD wrapper (esbuild has no UMD format)
- module.exports = module.exports.default as esbuild's CommonJS output of an ES module exports
	{default: alasql}, and require('alasql') must give a function.
- No keepNames: its helper runs every time a named function is created, which made SEARCH up to
	40 percent slower. extend and cloneDeep are function declarations, so they keep their names.
*/

import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import {fileURLToPath} from 'url';
import esbuild from 'esbuild';

const root = path.dirname(fileURLToPath(import.meta.url));
const dist = path.join(root, 'dist');
const generatedDir = path.join(root, 'src', 'generated');

// Without these esbuild bundles SheetJS into the Node build and fails on the Node and React
// Native modules. With them the require() calls stay in the output, lazy as before.
export const EXTERNALS = [
	'../modules/xlsx/xlsx',
	'fs',
	'path',
	'react-native',
	'react-native-fs',
	'react-native-fetch-blob',
	'cross-fetch',
];

const UMD_FIRST = '(function (root, factory) {';
const UMD_LAST = '}(this, function () {';
const TAIL = /\n\s*return alasql;\s*\n\}\)\);\s*$/;

// The worker files carry commented-out code and debug console.log lines, and nothing else removes
// them: they are joined as text, not bundled from source
export function stripComments(text) {
	return text
		.replace(/\/\*\/\*[\S\s]+?\*\//gim, '')
		.replace(/^\/\/[ \t]{2,}.*/gim, '')
		.replace(/\/\/.*?console\.log\(.*/gim, '')
		.replace(/\n[\s]+\n/gim, '\n\n');
}

// The worker files still carry the UMD wrapper of the old concatenation; the bundle gets its own
export function hasHead(text) {
	return text.includes(UMD_FIRST) && text.includes(UMD_LAST);
}
export function cutHead(text, file) {
	const a = text.indexOf(UMD_FIRST);
	const b = text.indexOf(UMD_LAST);
	if (a < 0 || b < a) throw new Error(file + ': the UMD head was not found');
	return text.slice(0, a) + text.slice(b + UMD_LAST.length);
}
export function cutTail(text, file) {
	if (!TAIL.test(text)) throw new Error(file + ': the UMD tail was not found');
	return text.replace(TAIL, '\n');
}

// The worker head assigns undeclared names, so it is not valid as a module and is joined as text
export function concatBody(files) {
	let text = '';
	for (const f of files) {
		let part = fs.readFileSync(path.join(root, f), 'utf8');
		if (hasHead(part)) part = cutHead(part, f);
		if (TAIL.test(part)) part = cutTail(part, f);
		text += part;
	}
	return {text: stripComments(text)};
}

// The utilities the grammar actions call by bare name (doubleq). The parser is made before the
// utilities exist, so each gets a forwarder that looks it up on alasql.utils when it is called.
export const PARSER_UTILS = {doubleq: 's'};

// The generated parser as a module: a function that makes the parser for one alasql object,
// because the grammar actions read alasql.options, alasql.fn and alasql.aggr by that name. The
// jison output stays what it is; this wraps it.
export function parserModule() {
	return (
		'// Generated by build.js from src/alasqlparser.js. Not committed; do not edit.\n' +
		'export default function makeParser(alasql) {\n' +
		Object.entries(PARSER_UTILS)
			.map(([u, p]) => `function ${u}(${p}) {\n\treturn alasql.utils.${u}(${p});\n}\n`)
			.join('') +
		fs.readFileSync(path.join(root, 'src', 'alasqlparser.js'), 'utf8') +
		'\nreturn alasqlparser;\n}\n'
	);
}

// CommonJS, for the same reason; the launcher is a module, because the main bundle installs it too
export function workerModule() {
	return `// Generated by build.js. Not committed; do not edit.
${concatBody(['src/worker/start.js']).text}
require('../worker/launcher.js').default(alasql);
${concatBody(['src/worker/finish.js']).text}
module.exports = alasql;
`;
}

export function banner() {
	return fs.readFileSync(path.join(root, 'src', 'copyright.js'), 'utf8');
}

// One source serves both the Node and the browser builds, so code that must not reach the browser
// is marked inside it instead of living in separate files. The markers are comments, so the source
// still runs unchanged in Node. Old browsers reject a function declared inside a block in strict
// code, which is why the parser's locateNearestErrorRecoveryRule becomes a variable.
export function forBrowser(text) {
	return text
		.replaceAll('//*not-for-browser/*', '/*not-for-browser/*')
		.replaceAll('/*only-for-browser/*', '//*only-for-browser/*')
		.replaceAll(
			'function locateNearestErrorRecoveryRule(state) {',
			'var locateNearestErrorRecoveryRule = function (state) {'
		);
}

// The markers must be applied before esbuild parses a file
const browserSource = {
	name: 'alasql-browser-source',
	setup(bundler) {
		bundler.onLoad({filter: /[\\/]src[\\/].*\.js$/}, args => ({
			contents: forBrowser(fs.readFileSync(args.path, 'utf8')),
			loader: 'js',
		}));
	},
};

export async function bundle(entry, {browser = false, minify = false, external = EXTERNALS} = {}) {
	const result = await esbuild.build({
		entryPoints: [entry],
		bundle: true,
		write: false,
		format: 'cjs',
		platform: browser ? 'browser' : 'node',
		external,
		minify,
		legalComments: 'inline',
		define: browser ? {__dirname: '""'} : undefined,
		plugins: browser ? [browserSource] : [],
		logLevel: 'silent',
	});
	if (result.errors.length) throw new Error(result.errors.map(e => e.text).join('\n'));
	// the output starts with its own "use strict" when the entry is an ES module; the head adds it
	return result.outputFiles[0].text.replace(/^"use strict";\n/, '');
}

// esbuild's cjs output of an ES module exports {default: alasql}; the package exports the function
export function defaultExport(code) {
	return code + '\nmodule.exports = module.exports.default;\n';
}

// esbuild has no UMD format, and the browser file has to work with AMD loaders, CommonJS and a
// plain <script> tag
export function umd(body, minified) {
	if (minified) {
		return `(function(root,factory){if(typeof define==="function"&&define.amd){define([],factory)}else if(typeof exports==="object"){module.exports=factory()}else{root.alasql=factory()}})(this,function(){var module={exports:{}},exports=module.exports;${body}
return module.exports});
`;
	}
	return `(function (root, factory) {
	if (typeof define === 'function' && define.amd) {
		define([], factory);
	} else if (typeof exports === 'object') {
		module.exports = factory();
	} else {
		root.alasql = factory();
	}
})(this, function () {
	var module = {exports: {}};
	var exports = module.exports;
${body}
	return module.exports;
});
`;
}

function write(name, text) {
	const file = path.join(dist, name);
	fs.mkdirSync(path.dirname(file), {recursive: true});
	fs.writeFileSync(file, text);
	const sha = crypto.createHash('sha256').update(text).digest('hex').slice(0, 12);
	console.log(
		`  ${name.padEnd(24)} ${String(Buffer.byteLength(text)).padStart(9)} bytes  sha256 ${sha}`
	);
}

export async function build() {
	console.log(`alasql with esbuild ${esbuild.version}`);

	fs.rmSync(dist, {recursive: true, force: true});
	fs.mkdirSync(path.join(dist, 'precompile'), {recursive: true});
	fs.mkdirSync(generatedDir, {recursive: true});

	const head = banner() + '"use strict";\n';
	fs.writeFileSync(path.join(generatedDir, 'parser.js'), parserModule());
	const entry = path.join(root, 'src', 'index.js');

	write('alasql.fs.js', head + defaultExport(await bundle(entry)));
	write('alasql.js', head + umd(defaultExport(await bundle(entry, {browser: true})), false));
	write(
		'alasql.min.js',
		head + umd(defaultExport(await bundle(entry, {browser: true, minify: true})), true)
	);

	// The worker was never strict: src/worker/start.js has no directive and assigns an undeclared
	// isArray
	const worker = path.join(generatedDir, 'worker.js');
	fs.writeFileSync(worker, workerModule());
	write(
		'alasql-worker.js',
		banner() + umd(await bundle(worker, {browser: true, minify: true}), true)
	);

	write(
		'precompile/index.js',
		await bundle(path.join(root, 'src', 'precompile', 'index.js'), {
			external: ['../../dist/alasql.fs.js'],
		})
	);

	for (const [from, to] of [
		['types/alasql.d.ts', 'alasql.d.ts'],
		['src/echo/alasql-echo.js', 'alasql-echo.js'],
		['src/prolog/alasql-prolog.js', 'alasql-prolog.js'],
	]) {
		write(to, fs.readFileSync(path.join(root, from), 'utf8'));
	}

	for (const f of fs.readdirSync(dist)) {
		const p = path.join(dist, f);
		if (fs.statSync(p).isFile() && fs.readFileSync(p, 'utf8').includes(root))
			throw new Error(`${f} contains the path of this checkout`);
	}
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	build().catch(e => {
		console.error(e && e.message ? e.message : e);
		process.exit(1);
	});
}
